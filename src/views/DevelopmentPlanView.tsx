import React, { useState } from 'react';
import {
  Edit3,
  Info,
  Plus,
  Sparkles,
  Trash2,
  X,
} from 'lucide-react';
import { PlanStatusIndicator, PriorityIndicator } from '../components/SemanticIndicators';
import { PRIORITY_LEVELS } from '../constants/categories';
import {
  DevelopmentPlanItem,
  PlanProgressStatus,
  PriorityLevel,
} from '../types';

interface DevelopmentPlanViewProps {
  planItems: DevelopmentPlanItem[];
  onAddPlanItem: (item: Omit<DevelopmentPlanItem, 'id'>) => void;
  onUpdatePlanItem: (item: DevelopmentPlanItem) => void;
  onDeletePlanItem: (id: string) => void;
  onRegenerateDraftFromSurvey: () => void;
}

const PLAN_STATUS_OPTIONS: PlanProgressStatus[] = [
  'Proposed',
  'Under Review',
  'Draft Prioritized',
  'In Implementation',
  'Completed',
];

export const DevelopmentPlanView: React.FC<DevelopmentPlanViewProps> = ({
  planItems,
  onAddPlanItem,
  onUpdatePlanItem,
  onDeletePlanItem,
  onRegenerateDraftFromSurvey,
}) => {
  const [modalOpen, setModalOpen] = useState(false);
  const [editingItem, setEditingItem] = useState<DevelopmentPlanItem | null>(null);

  const [identifiedIssue, setIdentifiedIssue] = useState('');
  const [category, setCategory] = useState('Healthcare Facilities');
  const [targetVillages, setTargetVillages] = useState('');
  const [proposedSolution, setProposedSolution] = useState('');
  const [priority, setPriority] = useState<PriorityLevel>('High');
  const [suggestedDepartment, setSuggestedDepartment] = useState('');
  const [estimatedCostRange, setEstimatedCostRange] = useState('₹50,000 – ₹1,50,000 (Illustrative)');
  const [suggestedTimeline, setSuggestedTimeline] = useState('Medium-term (3–6 Months)');
  const [progressStatus, setProgressStatus] = useState<PlanProgressStatus>('Proposed');
  const [expectedOutcome, setExpectedOutcome] = useState('');
  const [formError, setFormError] = useState<string | null>(null);

  const openCreateModal = () => {
    setEditingItem(null);
    setIdentifiedIssue('');
    setCategory('Village Infrastructure');
    setTargetVillages('');
    setProposedSolution('');
    setPriority('High');
    setSuggestedDepartment('Gram Panchayat Standing Committee & Engineering Wing');
    setEstimatedCostRange('₹50,000 – ₹1,50,000 (Illustrative)');
    setSuggestedTimeline('Medium-term (3–6 Months)');
    setProgressStatus('Proposed');
    setExpectedOutcome('');
    setFormError(null);
    setModalOpen(true);
  };

  const openEditModal = (item: DevelopmentPlanItem) => {
    setEditingItem(item);
    setIdentifiedIssue(item.identifiedIssue);
    setCategory(item.category);
    setTargetVillages(item.targetVillages);
    setProposedSolution(item.proposedSolution);
    setPriority(item.priority);
    setSuggestedDepartment(item.suggestedDepartment);
    setEstimatedCostRange(item.estimatedCostRange);
    setSuggestedTimeline(item.suggestedTimeline);
    setProgressStatus(item.progressStatus);
    setExpectedOutcome(item.expectedOutcome);
    setFormError(null);
    setModalOpen(true);
  };

  const handleSave = (e: React.FormEvent) => {
    e.preventDefault();
    if (!identifiedIssue.trim() || !proposedSolution.trim() || !expectedOutcome.trim()) {
      setFormError('Please complete Identified Issue, Proposed Solution, and Expected Outcome.');
      return;
    }

    const costWithLabel = estimatedCostRange.toLowerCase().includes('illustrative')
      ? estimatedCostRange.trim()
      : `${estimatedCostRange.trim()} (Illustrative)`;

    if (editingItem) {
      onUpdatePlanItem({
        ...editingItem,
        identifiedIssue: identifiedIssue.trim(),
        category: category.trim() || 'General Development',
        targetVillages: targetVillages.trim() || 'All Surveyed Localities',
        proposedSolution: proposedSolution.trim(),
        priority,
        suggestedDepartment: suggestedDepartment.trim() || 'Gram Panchayat Standing Committee',
        estimatedCostRange: costWithLabel,
        suggestedTimeline: suggestedTimeline.trim() || 'Medium-term (3–6 Months)',
        progressStatus,
        expectedOutcome: expectedOutcome.trim(),
      });
    } else {
      onAddPlanItem({
        identifiedIssue: identifiedIssue.trim(),
        category: category.trim() || 'General Development',
        targetVillages: targetVillages.trim() || 'All Surveyed Localities',
        proposedSolution: proposedSolution.trim(),
        priority,
        suggestedDepartment: suggestedDepartment.trim() || 'Gram Panchayat Standing Committee',
        estimatedCostRange: costWithLabel,
        suggestedTimeline: suggestedTimeline.trim() || 'Medium-term (3–6 Months)',
        progressStatus,
        expectedOutcome: expectedOutcome.trim(),
        isAutoGeneratedDraft: false,
      });
    }

    setModalOpen(false);
  };

  return (
    <div className="space-y-6">
      {/* Header & Controls */}
      <div className="flex flex-col lg:flex-row lg:items-end justify-between gap-4">
        <div>
          <p className="text-xs font-medium text-teal-700">
            Actionable Gram Panchayat Development Plan (GPDP) Draft Workspace
          </p>
          <h1 className="text-2xl sm:text-3xl font-bold tracking-tight text-slate-900 mt-1">
            Village Development Plan
          </h1>
          <p className="text-sm text-slate-600 mt-1 max-w-2xl">
            Translate high-frequency household survey findings into structured project proposals with timelines, suggested committees, and expected outcomes.
          </p>
        </div>

        <div className="flex flex-wrap items-center gap-2.5 shrink-0">
          <button
            type="button"
            onClick={onRegenerateDraftFromSurvey}
            className="inline-flex items-center gap-2 px-4 py-2.5 rounded-lg border border-slate-300 bg-white text-xs font-semibold text-slate-800 hover:bg-slate-50 transition-colors whitespace-nowrap cursor-pointer"
          >
            <Sparkles className="w-3.5 h-3.5 text-teal-700" />
            <span>Generate Draft from Survey Findings</span>
          </button>
          <button
            type="button"
            onClick={openCreateModal}
            className="inline-flex items-center gap-2 px-4 py-2.5 rounded-lg bg-teal-700 text-xs font-semibold text-white hover:bg-teal-800 transition-colors whitespace-nowrap cursor-pointer"
          >
            <Plus className="w-4 h-4" />
            <span>Add Action Item</span>
          </button>
        </div>
      </div>

      {/* Illustrative Estimate & Authority Verification Disclaimer */}
      <div className="rounded-xl border border-amber-200 bg-amber-50/70 px-4 py-3.5 flex items-start gap-3">
        <Info className="w-4 h-4 text-amber-700 mt-0.5 shrink-0" />
        <p className="text-xs text-amber-950 leading-relaxed">
          <span className="font-semibold">Draft Proposals Requiring Verification:</span> All generated and manually added development plan items are academic CSP draft proposals. Cost ranges are strictly <span className="font-semibold">illustrative estimates</span>, and suggested departments require technical inspection and Gram Sabha sanction before implementation.
        </p>
      </div>

      {/* Summary Strip */}
      <div className="bg-white border border-slate-200 rounded-xl grid grid-cols-2 sm:grid-cols-4 divide-y sm:divide-y-0 sm:divide-x divide-slate-200">
        <div className="p-4">
          <div className="text-xs text-slate-500">Total Action Proposals</div>
          <div className="mt-1 text-2xl font-bold font-mono tabular-nums text-slate-900">
            {planItems.length}
          </div>
        </div>
        <div className="p-4">
          <div className="text-xs text-slate-500">Critical / High Priority</div>
          <div className="mt-1 text-2xl font-bold font-mono tabular-nums text-amber-700">
            {planItems.filter((p) => p.priority === 'Critical' || p.priority === 'High').length}
          </div>
        </div>
        <div className="p-4">
          <div className="text-xs text-slate-500">In Implementation</div>
          <div className="mt-1 text-2xl font-bold font-mono tabular-nums text-teal-700">
            {planItems.filter((p) => p.progressStatus === 'In Implementation').length}
          </div>
        </div>
        <div className="p-4">
          <div className="text-xs text-slate-500">Completed Actions</div>
          <div className="mt-1 text-2xl font-bold font-mono tabular-nums text-emerald-700">
            {planItems.filter((p) => p.progressStatus === 'Completed').length}
          </div>
        </div>
      </div>

      {/* Action Plan Table */}
      <div className="bg-white border border-slate-200 rounded-xl overflow-hidden">
        {planItems.length > 0 ? (
          <div className="overflow-x-auto">
            <table className="w-full text-left border-collapse text-xs">
              <thead>
                <tr className="border-b border-slate-200 bg-slate-50 text-[11px] font-semibold text-slate-600 whitespace-nowrap">
                  <th className="py-3.5 px-4 min-w-[200px]">Identified Issue &amp; Villages</th>
                  <th className="py-3.5 px-4 min-w-[240px]">Proposed Solution &amp; Expected Outcome</th>
                  <th className="py-3.5 px-3">Priority</th>
                  <th className="py-3.5 px-3 min-w-[180px]">Suggested Responsible Dept.</th>
                  <th className="py-3.5 px-3 min-w-[150px]">Illustrative Cost &amp; Timeline</th>
                  <th className="py-3.5 px-3">Progress Status</th>
                  <th className="py-3.5 px-4 text-right">Manage</th>
                </tr>
              </thead>
              <tbody className="divide-y divide-slate-100 align-top">
                {planItems.map((item) => (
                  <tr key={item.id} className="hover:bg-slate-50/70 transition-colors">
                    <td className="py-4 px-4 max-w-xs">
                      <div className="font-semibold text-slate-900">{item.identifiedIssue}</div>
                      <div className="text-[11px] text-slate-500 mt-1">
                        {item.targetVillages} · {item.isAutoGeneratedDraft ? 'Draft Proposal' : 'Admin Entry'}
                      </div>
                      {item.evidenceNote && (
                        <div className="text-[11px] text-teal-700 mt-0.5">{item.evidenceNote}</div>
                      )}
                    </td>
                    <td className="py-4 px-4 max-w-sm space-y-1.5">
                      <p className="text-slate-800 leading-relaxed">{item.proposedSolution}</p>
                      <p className="text-[11px] text-slate-500">
                        <span className="font-semibold text-slate-700">Outcome:</span> {item.expectedOutcome}
                      </p>
                    </td>
                    <td className="py-4 px-3">
                      <PriorityIndicator priority={item.priority} />
                    </td>
                    <td className="py-4 px-3 text-slate-700 max-w-[200px] leading-relaxed">
                      {item.suggestedDepartment}
                    </td>
                    <td className="py-4 px-3 whitespace-nowrap">
                      <div className="font-mono tabular-nums font-semibold text-slate-800">
                        {item.estimatedCostRange}
                      </div>
                      <div className="text-[11px] text-slate-500 mt-0.5">
                        {item.suggestedTimeline}
                      </div>
                    </td>
                    <td className="py-4 px-3">
                      <div className="space-y-1.5">
                        <PlanStatusIndicator status={item.progressStatus} />
                        <select
                          value={item.progressStatus}
                          aria-label={`Change progress status for ${item.identifiedIssue}`}
                          onChange={(e) =>
                            onUpdatePlanItem({
                              ...item,
                              progressStatus: e.target.value as PlanProgressStatus,
                            })
                          }
                          className="block w-full px-2 py-1 text-[11px] rounded border border-slate-200 bg-white text-slate-700"
                        >
                          {PLAN_STATUS_OPTIONS.map((opt) => (
                            <option key={opt} value={opt}>
                              {opt}
                            </option>
                          ))}
                        </select>
                      </div>
                    </td>
                    <td className="py-4 px-4 text-right whitespace-nowrap">
                      <div className="inline-flex items-center gap-1.5">
                        <button
                          type="button"
                          onClick={() => openEditModal(item)}
                          className="p-1.5 rounded-md text-slate-600 hover:text-teal-800 hover:bg-teal-50 transition-colors cursor-pointer"
                          title="Edit plan item"
                        >
                          <Edit3 className="w-4 h-4" />
                        </button>
                        <button
                          type="button"
                          onClick={() => onDeletePlanItem(item.id)}
                          className="p-1.5 rounded-md text-slate-500 hover:text-red-700 hover:bg-red-50 transition-colors cursor-pointer"
                          title="Remove plan item"
                        >
                          <Trash2 className="w-4 h-4" />
                        </button>
                      </div>
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        ) : (
          <div className="py-14 px-4 text-center space-y-3">
            <p className="text-sm font-semibold text-slate-800">
              No development plan proposals yet
            </p>
            <p className="text-xs text-slate-500 max-w-md mx-auto">
              Generate a draft village development plan automatically from the top survey findings or add custom items manually.
            </p>
            <button
              type="button"
              onClick={onRegenerateDraftFromSurvey}
              className="px-4 py-2 rounded-lg bg-teal-700 text-white text-xs font-semibold hover:bg-teal-800 cursor-pointer"
            >
              Generate Draft Plan from Survey
            </button>
          </div>
        )}
      </div>

      {/* Add / Edit Plan Item Modal */}
      {modalOpen && (
        <div
          className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-slate-900/60"
          role="dialog"
          aria-modal="true"
        >
          <form
            onSubmit={handleSave}
            className="bg-white border border-slate-200 rounded-xl max-w-xl w-full max-h-[90vh] overflow-y-auto shadow-xl p-6 space-y-4"
          >
            <div className="flex items-center justify-between border-b border-slate-200 pb-3">
              <h2 className="text-base font-bold text-slate-900">
                {editingItem ? 'Edit Development Plan Proposal' : 'Add Development Plan Proposal'}
              </h2>
              <button
                type="button"
                onClick={() => setModalOpen(false)}
                className="p-1.5 rounded-lg text-slate-500 hover:bg-slate-100 cursor-pointer"
                aria-label="Close modal"
              >
                <X className="w-4 h-4" />
              </button>
            </div>

            {formError && (
              <div className="p-3 rounded-lg border border-red-200 bg-red-50 text-xs text-red-800">
                {formError}
              </div>
            )}

            <div className="grid grid-cols-1 sm:grid-cols-2 gap-3.5 text-xs">
              <div className="sm:col-span-2">
                <label className="block font-semibold text-slate-700 mb-1">
                  Identified Issue <span className="text-red-600">*</span>
                </label>
                <input
                  type="text"
                  required
                  value={identifiedIssue}
                  onChange={(e) => setIdentifiedIssue(e.target.value)}
                  placeholder="e.g., Lack of Primary Health Sub-Centre OPD Schedule"
                  className="w-full px-3 py-2 rounded-lg border border-slate-300"
                />
              </div>

              <div>
                <label className="block font-semibold text-slate-700 mb-1">
                  Target Villages / Wards
                </label>
                <input
                  type="text"
                  value={targetVillages}
                  onChange={(e) => setTargetVillages(e.target.value)}
                  placeholder="e.g., Venkatapuram, Kothapalli"
                  className="w-full px-3 py-2 rounded-lg border border-slate-300"
                />
              </div>

              <div>
                <label className="block font-semibold text-slate-700 mb-1">
                  Priority Level
                </label>
                <select
                  value={priority}
                  onChange={(e) => setPriority(e.target.value as PriorityLevel)}
                  className="w-full px-3 py-2 rounded-lg border border-slate-300 bg-white"
                >
                  {PRIORITY_LEVELS.map((p) => (
                    <option key={p} value={p}>
                      {p}
                    </option>
                  ))}
                </select>
              </div>

              <div className="sm:col-span-2">
                <label className="block font-semibold text-slate-700 mb-1">
                  Proposed Solution <span className="text-red-600">*</span>
                </label>
                <textarea
                  rows={3}
                  required
                  value={proposedSolution}
                  onChange={(e) => setProposedSolution(e.target.value)}
                  placeholder="Describe actionable, affordable solution for local authorities..."
                  className="w-full px-3 py-2 rounded-lg border border-slate-300"
                />
              </div>

              <div className="sm:col-span-2">
                <label className="block font-semibold text-slate-700 mb-1">
                  Suggested Responsible Department / Committee
                </label>
                <input
                  type="text"
                  value={suggestedDepartment}
                  onChange={(e) => setSuggestedDepartment(e.target.value)}
                  className="w-full px-3 py-2 rounded-lg border border-slate-300"
                />
              </div>

              <div>
                <label className="block font-semibold text-slate-700 mb-1">
                  Estimated Cost Range (Illustrative)
                </label>
                <input
                  type="text"
                  value={estimatedCostRange}
                  onChange={(e) => setEstimatedCostRange(e.target.value)}
                  className="w-full px-3 py-2 rounded-lg border border-slate-300"
                />
              </div>

              <div>
                <label className="block font-semibold text-slate-700 mb-1">
                  Suggested Timeline
                </label>
                <input
                  type="text"
                  value={suggestedTimeline}
                  onChange={(e) => setSuggestedTimeline(e.target.value)}
                  className="w-full px-3 py-2 rounded-lg border border-slate-300"
                />
              </div>

              <div>
                <label className="block font-semibold text-slate-700 mb-1">
                  Progress Status
                </label>
                <select
                  value={progressStatus}
                  onChange={(e) => setProgressStatus(e.target.value as PlanProgressStatus)}
                  className="w-full px-3 py-2 rounded-lg border border-slate-300 bg-white"
                >
                  {PLAN_STATUS_OPTIONS.map((opt) => (
                    <option key={opt} value={opt}>
                      {opt}
                    </option>
                  ))}
                </select>
              </div>

              <div>
                <label className="block font-semibold text-slate-700 mb-1">
                  Sector / Category
                </label>
                <input
                  type="text"
                  value={category}
                  onChange={(e) => setCategory(e.target.value)}
                  className="w-full px-3 py-2 rounded-lg border border-slate-300"
                />
              </div>

              <div className="sm:col-span-2">
                <label className="block font-semibold text-slate-700 mb-1">
                  Expected Community Outcome <span className="text-red-600">*</span>
                </label>
                <input
                  type="text"
                  required
                  value={expectedOutcome}
                  onChange={(e) => setExpectedOutcome(e.target.value)}
                  placeholder="e.g., Reliable daily drinking water access for 120 households"
                  className="w-full px-3 py-2 rounded-lg border border-slate-300"
                />
              </div>
            </div>

            <div className="pt-3 border-t border-slate-200 flex items-center justify-end gap-2.5">
              <button
                type="button"
                onClick={() => setModalOpen(false)}
                className="px-4 py-2 rounded-lg border border-slate-300 text-xs font-semibold text-slate-700 hover:bg-slate-50 cursor-pointer"
              >
                Cancel
              </button>
              <button
                type="submit"
                className="px-4 py-2 rounded-lg bg-teal-700 text-xs font-semibold text-white hover:bg-teal-800 cursor-pointer"
              >
                {editingItem ? 'Save Changes' : 'Add Plan Proposal'}
              </button>
            </div>
          </form>
        </div>
      )}
    </div>
  );
};
